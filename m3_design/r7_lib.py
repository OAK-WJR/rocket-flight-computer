def _outline(z, pts):
    o = z.Outline()
    o.RemoveAllContours()
    o.NewOutline()
    for x, y in pts:
        o.Append(MM(x), MM(y))


def rect(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def zones(b):
    """Extend the board-wide GND pours over the strip, add In2 GND under it, clip BAT_IN to the left strip, give
    3V3 the freed aft band on In2, cut In1 under the launches and name the module keep-out areas."""
    import r5_pcb as base
    named = {z.GetZoneName(): z for z in b.Zones()}
    for name in ('GND_F', 'GND_B', 'GND_In1'):
        _outline(named[name], rect(0.3, 0.3, 45.7, 117.7))
    # BAT_IN In2: R6's aft rectangle (x 0.3-15, R7 y 18.3-32.6) is not needed by any BAT_IN item (R80 and D8 reach
    # BAT_IN through B.Cu and the via at (9.2, 36.05); the two vias at y 26.6 lie inside the left strip).
    _outline(named['R6_BAT_IN_In2'], [(0.3, 26.0), (9.9, 26.0), (9.9, 80.0), (14.0, 84.1), (14.0, 106.6),
                                      (32.2, 106.6), (32.2, 115.5), (8.9, 115.5), (8.9, 112.0), (0.3, 112.0)])
    # 3V3 In2: the R6 outline plus a lobe forward of the strip (x 9.9-14, y 23.9-27) where FB30's feed via drops in.
    # FB31 takes 3V3 on F.Cu from R161.1 (r7_route.radio); In2 east of the lobe (y 23.5-27) stays free for the
    # east-west links the strip displaced (r7_route.reroute).
    _outline(named['3V3_In2'], [(9.9, 23.9), (14.0, 23.9), (14.0, 27.0), (34.5, 27.0), (34.5, 70.2), (14.0, 70.2),
                                (14.0, 79.5), (8.9, 79.5), (8.9, 70.2), (9.2, 70.2), (9.2, 27.0), (9.9, 27.0)])
    base.add_zone(b, 'GND', (pcbnew.In2_Cu,), rect(0.3, 0.3, 45.7, STRIP_Y), 7, 'R7_GND_In2_strip',
                  clr=0.25, minw=0.2, conn=pcbnew.ZONE_CONNECTION_FULL)
    for ref, x in IN1_LAUNCH.items():
        base.rule_area(b, f'R7_{ref}_launch_In1', (pcbnew.In1_Cu,), rect(x - 0.9, 0.0, x + 0.9, 4.6), fill=True)
    base.rule_area(b, 'U30_KEEPOUT', (pcbnew.F_Cu, pcbnew.In1_Cu), rect(*U30_KEEPOUT))
    base.rule_area(b, 'U31_KEEPOUT', base.CU4, rect(*U31_KEEPOUT))
