#!/usr/bin/env python3
"""Build the R8 board's GND stitching copper (M3-ASSY-R8, build step 7; R8_DECISIONS D62 on).

usage: <KiCad python3> -I m3_design/r8_ground.py [--board m3_design/assembly_review/m3.kicad_pcb] [--table TSV]

Draws every row of m3_design/r8_ground.tsv on the step-6 board (r8_route.py's links output), in place: the strip
fence row (D16), spike (d)'s two stitching vias, spike (a)'s C24 GND stub and via, a GND via beside every power-net
layer change that had none, the stitching grid (r8_plan step 7: <= 4 mm), the vias that give every outer GND pour
island two, the vias that bring the outer GND pours within reach, and the pour trims (fill keep-out rule areas) that
remove the GND pieces enclosed by lanes where no second via fits. The table is generated by
m3_design/assembly_review/sources/r8_design/step7/make_ground.py (its docstring has the legality rules and the
order); the gate is r8_ground_check.py.

Before the fill it gives the through-hole GND pins of RELIEF_PADS the board's THT thermal relief (fix pass 2,
R8P2-DFM-01 / R8P2-INTEGRITY-01, D101): J123.2 was kept solid because DRC reported starved_thermal on the step-6 board,
but on this stage's final GND copper the relief resolves the project's min_resolved_spokes (2 on B.Cu, >= 4 on F.Cu and
In1), so REQUIREMENTS M2's rule applies. It is set here, where the final copper exists, not in r8_pcb.py (step 4),
because the step-6 gates run DRC before the stitching vias and fill that give it its spokes.

The stage runs once (no table item may exist before it), keeps the 12 rigid digests (check_r8 D15: no new GND via aft
of y 23.5 but on the fence row), asserts every via it adds stays on GND after the native fill (a via on foreign copper
would be re-netted) and that each track ends where the table says. Deterministic (fixed KIID seed): a rebuild
reproduces the board byte for byte.
"""
import argparse
import csv
import sys
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'm3_design'))
sys.path.insert(0, str(ROOT / 'tools'))
import check_r8  # noqa: E402

PROJECT = ROOT / 'm3_design/assembly_review'
TABLE = ROOT / 'm3_design/r8_ground.tsv'
MM, mm = pcbnew.FromMM, pcbnew.ToMM
LAYER = {'F': pcbnew.F_Cu, 'B': pcbnew.B_Cu}
KIID_SEED = 8815              # r8_route.py's families use 8806-8814
EPS = 1e-6
RELIEF_PADS = (('J123', '2'),)   # THT GND pins relieved on the final copper (D101); make_ground.py models the same


def relieve(b, strict=True):
    """Give RELIEF_PADS the zones' THT thermal relief (INHERITED): R7 / step 4 left them FULL (strict: asserted)."""
    for ref, num in RELIEF_PADS:
        pads = [p for p in b.FindFootprintByReference(ref).Pads() if p.GetNumber() == num]
        assert len(pads) == 1 and pads[0].GetNetname() == 'GND', (ref, num)
        c = pads[0].GetLocalZoneConnection()
        assert c == pcbnew.ZONE_CONNECTION_FULL or (not strict and c == pcbnew.ZONE_CONNECTION_INHERITED), \
            (ref, num, 'expected the step-4 FULL connection')
        pads[0].SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_INHERITED)


def P(x, y):
    return pcbnew.VECTOR2I(MM(x), MM(y))


def r4(v):
    return round(v, 4)


def read(path=TABLE):
    with open(path) as fh:
        return list(csv.DictReader((line for line in fh if not line.startswith('#')), delimiter='\t'))


def octilinear(a, b):
    dx, dy = abs(b[0] - a[0]), abs(b[1] - a[1])
    return dx < EPS or dy < EPS or abs(dx - dy) < EPS


def existing(b, rows):
    """Table items already on the board (the stage runs once)."""
    vias = {(r4(mm(t.GetPosition().x)), r4(mm(t.GetPosition().y))) for t in b.GetTracks() if t.GetClass() == 'PCB_VIA'}
    ends = {(r4(mm(t.GetStart().x)), r4(mm(t.GetStart().y)), r4(mm(t.GetEnd().x)), r4(mm(t.GetEnd().y)))
            for t in b.GetTracks() if t.GetClass() != 'PCB_VIA'}
    names = {z.GetZoneName() for z in b.Zones() if z.GetIsRuleArea()}
    out = []
    for r in rows:
        if r['item'] == 'trim' and r['basis'].split()[1] in names:
            out.append(r)
        if r['item'] == 'via' and (float(r['x0']), float(r['y0'])) in vias:
            out.append(r)
        if r['item'] == 'track' and (float(r['x0']), float(r['y0']), float(r['x1']), float(r['y1'])) in ends:
            out.append(r)
    return out


def draw(b, rows):
    gnd = b.FindNet('GND')
    assert gnd is not None and gnd.GetNetCode() > 0
    added, seen = [], set()
    for r in rows:
        assert r['net'] == 'GND', f'r8_ground draws GND only: {r}'
        if r['item'] == 'via':
            q = (r4(float(r['x0'])), r4(float(r['y0'])))
            assert q not in seen, f'two vias at {q}'
            seen.add(q)
            d, drill = (float(v) for v in r['size'].split('/'))
            assert r['layer'] == 'FB', r
            v = pcbnew.PCB_VIA(b)
            v.SetPosition(P(*q))
            v.SetWidth(MM(d))
            v.SetDrill(MM(drill))
            v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
            v.SetNet(gnd)
            b.Add(v)
            added.append(q)
        elif r['item'] == 'track':
            a = (r4(float(r['x0'])), r4(float(r['y0'])))
            c = (r4(float(r['x1'])), r4(float(r['y1'])))
            assert a != c and octilinear(a, c), f'track {a}-{c} is zero-length or not 0 / 45 / 90 degrees'
            t = pcbnew.PCB_TRACK(b)
            t.SetStart(P(*a))
            t.SetEnd(P(*c))
            t.SetWidth(MM(float(r['size'])))
            t.SetLayer(LAYER[r['layer']])
            t.SetNet(gnd)
            b.Add(t)
        elif r['item'] == 'trim':
            name = r['basis'].split()[1]
            assert name.startswith('R8_POUR_TRIM_G'), r
            pts = [tuple(float(v) for v in p.split(',')) for p in r['points'].split()]
            assert len(pts) >= 3, r
            z = pcbnew.ZONE(b)
            z.SetIsRuleArea(True)
            z.SetLayer(LAYER[r['layer']])
            z.SetZoneName(name)
            z.SetDoNotAllowZoneFills(True)
            z.SetDoNotAllowTracks(False)
            z.SetDoNotAllowVias(False)
            z.SetDoNotAllowPads(False)
            z.SetDoNotAllowFootprints(False)
            ol = z.Outline()
            ol.NewOutline()
            for x, y in pts:
                ol.Append(MM(x), MM(y))
            b.Add(z)
        else:
            raise AssertionError(f'unknown item {r}')
    return added


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--board', type=Path, default=PROJECT / 'm3.kicad_pcb')
    ap.add_argument('--table', type=Path, default=TABLE)
    args = ap.parse_args()
    board = args.board.resolve()
    for ext in ('.kicad_pro', '.kicad_dru'):
        assert board.with_suffix(ext).is_file(), f'{board.with_suffix(ext).name} must sit beside the board'
    rows = read(args.table)
    b = pcbnew.LoadBoard(str(board))
    issues, _ = check_r8.rigid(b)
    assert not issues, issues
    dup = existing(b, rows)
    assert not dup, f'{len(dup)} table items already on the board (run r8_ground.py once, on the step-6 board)'
    pcbnew.KIID.SeedGenerator(KIID_SEED)
    relieve(b)
    for z in b.Zones():
        if not z.GetIsRuleArea():
            z.UnFill()                     # stale fills would re-net new vias (spike (c) pitfall)
    added = draw(b, rows)
    b.BuildConnectivity()
    assert pcbnew.ZONE_FILLER(b).Fill(b.Zones()), 'native zone fill failed'
    b.BuildConnectivity()
    moved = [(q, v.GetNetname()) for v in b.GetTracks() if v.GetClass() == 'PCB_VIA'
             for q in [(r4(mm(v.GetPosition().x)), r4(mm(v.GetPosition().y)))] if q in set(added) and
             v.GetNetname() != 'GND']
    assert not moved, f'connectivity re-netted GND vias (a via sits on foreign copper): {moved}'
    assert pcbnew.SaveBoard(str(board), b, True), 'save failed'
    b = pcbnew.LoadBoard(str(board))
    issues, digests = check_r8.rigid(b)
    assert not issues, issues
    tracks = sum(1 for r in rows if r['item'] == 'track')
    trims = sum(1 for r in rows if r['item'] == 'trim')
    print(f'r8_ground: {len(added)} GND vias, {tracks} GND track(s), {trims} pour trims, '
          f'rigid digests {len(digests)}/12 equal R7')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
