#!/usr/bin/env python3
"""Build the R9 board's ground (M3-ASSY-R9, build step 8) on the step-7 board.

usage: <KiCad python3> -I m3_design/r9_ground.py [--board m3_design/assembly_review/m3.kicad_pcb] [--table TSV]
       [--out OUT]        (--out: design aid, save there instead of --board; r9_build.sh never passes it)

r9_plan.md section 4 step 8; R9_DECISIONS.md D-S8-*. The board is rebuilt in place (the project's m3.kicad_pro and
m3.kicad_dru apply while it is filled). Two parts:

  pours   the RF strip's F.Cu, B.Cu and In1 GND pours (r9_rf.pours, D-S4-07: x 0.3-45.7, y 0.3-23.0) become the
          board's GND pours on those layers: the same zones, settings and priorities (F / B: priority 0, 0.15 mm
          clearance and minimum width, THT thermal 0.5 / 0.5; In1: priority 1, 0.25 / 0.2, thermal 0.25 / 0.4), the
          outline grown to x 0.3-45.7, y 0.3-101.7 (the In2 GND pours' extent, r9_power), renamed R9_GND_F / _B /
          _In1 (D-S8-01). The power pours (priority 10-20) and the RF keep-outs keep precedence; the DRU's fill
          margins keep every pyro rule plus its margin (D-S5-12).
  table   m3_design/r9_ground.tsv, drawn in its order: GND stitching vias (0.5 / 0.3 mm, VIA_SIG) and GND straps
          (tracks), each row with its basis. The table is generated by m3_design/r9_ground_aid.py (design aid; its
          docstring has the legality rules and the stages) and frozen; the step gate is r9_ground_check.py.
  crystal the In2 void under the crystal (Y1_In2_keepout, R5 V1) becomes the oscillator's local ground plane
          (D-S8-20; ST AN2867 Rev 10 section 5.1, "a dedicated underneath ground plane"): the rule area keeps In2
          tracks out and no longer bars fills, and a GND zone with its outline (XTAL_ZONE, R9_GND_In2's settings,
          priority over the 3V3 region) fills it, so no 3V3 or other net's copper lies on In2 under Y1, C25 and C26;
          the plane steps back from the area's edge where a critical-reference B.Cu track runs just outside it, so the
          3V3 fill stays under that track as with the void (xtal_outline: NRST's run to C24.1).
  vias    every via keeps its pads only on the copper layers it connects (KiCad: remove unconnected layers, keep the
          start and end layers; D-S8-19, R4 E4-F1's precedent), so the In1 / In2 planes clear a via's hole by the
          board's 0.25 mm hole clearance instead of an unconnected ring plus the zone clearance (critical-reference
          antipads r 0.40 instead of 0.50 mm; JLC: inner-layer via hole to copper >= 0.2 mm).

The stage runs once (no R9_GND_F / _B / _In1 zone and no table item may exist before it), draws GND only, asserts
that no table via sits inside a non-GND F.Cu / B.Cu fill and that every via it adds is still on GND after the native
fill (a via on foreign copper would be re-netted), and that each track ends where the table says. Deterministic
(fixed KIID seed, table only): a rebuild reproduces the board byte for byte.
"""
import argparse
import csv
import math
import sys
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import critical_reference as CR  # noqa: E402
PROJECT = ROOT / 'm3_design/assembly_review'
TABLE = ROOT / 'm3_design/r9_ground.tsv'
MM, mm = pcbnew.FromMM, pcbnew.ToMM
KIID_SEED = 9908                 # r9_pcb 9903, r9_rf 9904, r9_pyro 9905, r9_power 9906, r9_route families 9910-9919
LAYER = {'F': pcbnew.F_Cu, 'B': pcbnew.B_Cu}
VIA = (0.5, 0.3)                 # r9_route.VIA_SIG: the board's signal and GND-partner via (R8's stitching via)
EPS = 1e-6

# The strip pours this step grows (r9_rf.pours: name, layer, priority, clearance, minimum width, pad connection,
# thermal gap, spoke width) and their board-wide names and outline (D-S8-01).
POURS = (('R9_GND_F_strip', 'R9_GND_F', pcbnew.F_Cu, 0, 0.15, 0.15, pcbnew.ZONE_CONNECTION_THT_THERMAL, 0.5, 0.5),
         ('R9_GND_B_strip', 'R9_GND_B', pcbnew.B_Cu, 0, 0.15, 0.15, pcbnew.ZONE_CONNECTION_THT_THERMAL, 0.5, 0.5),
         ('R9_GND_In1_strip', 'R9_GND_In1', pcbnew.In1_Cu, 1, 0.25, 0.2, pcbnew.ZONE_CONNECTION_THERMAL, 0.25, 0.4))
STRIP_BOX = (0.3, 0.3, 45.7, 23.0)
BOARD_BOX = (0.3, 0.3, 45.7, 101.7)
# The crystal's local In2 ground plane (D-S8-20): the rule area step 3 carries from R8 (R5 V1) and the zone that fills
# it (name, priority: over R9_3V3_In2's 10, under the RAW_ACT / BAT_IN regions' 12; settings copied from XTAL_LIKE).
XTAL_AREA = 'Y1_In2_keepout'
XTAL_ZONE = ('R9_GND_In2_Y1', 11)
XTAL_LIKE = 'R9_GND_In2'
# the rule area's flags before / after this step: (tracks, vias, pads, zone fills, footprints) barred
XTAL_FLAGS_STEP3 = (False, False, False, True, False)
XTAL_FLAGS = (True, False, False, False, False)
# A B.Cu track of critical_reference's R6 / extended nets lying wholly outside the area takes a notch out of the plane:
# its box grown by its half width + XTAL_REF_GAP (the plane's 0.25 mm clearance + 0.05), so the 3V3 fill (0.25 mm off the
# plane) still reaches 0.05 mm past the track's edge (the track keeps its In2 3V3 reference, as with the void). Elsewhere
# the 3V3 fill keeps its 0.25 mm outside the area, so tracks crossing into it (HSE_IN, QSPI_NCS's R10 branch) cross
# the gap inside their own via antipads.
XTAL_REF_GAP = 0.3
VIA_MODE = pcbnew.UNCONNECTED_LAYER_MODE_REMOVE_EXCEPT_START_AND_END       # D-S8-19


def r4(v):
    return round(v + 0.0, 4)


def P(x, y):
    return pcbnew.VECTOR2I(MM(x), MM(y))


def box_points(box):
    x0, y0, x1, y1 = box
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def outline(z):
    o = z.Outline()
    return [(r4(mm(o.CVertex(i).x)), r4(mm(o.CVertex(i).y))) for i in range(o.TotalVertices())]


def grow_pours(b):
    """The strip pours become the board's F.Cu / B.Cu / In1 GND pours (module docstring). Asserts each one's step-4
    settings and outline first, so a changed strip pour stops the build."""
    zones = {z.GetZoneName(): z for z in b.Zones() if not z.GetIsRuleArea()}
    for old, new, lid, prio, clr, minw, conn, gap, spoke in POURS:
        assert new not in zones, f'{new} already on the board (r9_ground.py runs once, on the step-7 board)'
        z = zones.get(old)
        assert z is not None, f'{old} missing (r9_rf.pours)'
        layers = list(z.GetLayerSet().Seq())
        got = (z.GetNetname(), layers[0] if len(layers) == 1 else None,
               z.GetAssignedPriority(), r4(mm(z.GetLocalClearance())), r4(mm(z.GetMinThickness())),
               z.GetPadConnection(), r4(mm(z.GetThermalReliefGap())), r4(mm(z.GetThermalReliefSpokeWidth())),
               z.GetIslandRemovalMode(), outline(z))
        want = ('GND', lid, prio, clr, minw, conn, gap, spoke, pcbnew.ISLAND_REMOVAL_MODE_ALWAYS, box_points(STRIP_BOX))
        assert got == want, f'{old}: {got} is not r9_rf.pours\' {want}'
        o = z.Outline()
        o.RemoveAllContours()
        o.NewOutline()
        for x, y in box_points(BOARD_BOX):
            o.Append(MM(x), MM(y))
        z.SetZoneName(new)


def read(path=TABLE):
    with open(path) as fh:
        return list(csv.DictReader((line for line in fh if not line.startswith('#')), delimiter='\t'))


def octilinear(a, c):
    dx, dy = abs(c[0] - a[0]), abs(c[1] - a[1])
    return dx < EPS or dy < EPS or abs(dx - dy) < EPS


def existing(b, rows):
    """Table items already on the board (the stage runs once)."""
    vias = {(r4(mm(t.GetPosition().x)), r4(mm(t.GetPosition().y))) for t in b.GetTracks() if t.GetClass() == 'PCB_VIA'}
    ends = {(r4(mm(t.GetStart().x)), r4(mm(t.GetStart().y)), r4(mm(t.GetEnd().x)), r4(mm(t.GetEnd().y)))
            for t in b.GetTracks() if t.GetClass() != 'PCB_VIA'}
    out = []
    for r in rows:
        if r['item'] == 'via' and (r4(float(r['x0'])), r4(float(r['y0']))) in vias:
            out.append(r)
        if r['item'] == 'track' and tuple(r4(float(r[k])) for k in ('x0', 'y0', 'x1', 'y1')) in ends:
            out.append(r)
    return out


def draw(b, rows):
    """Draw the table's rows; returns the via centres added."""
    gnd = b.FindNet('GND')
    assert gnd is not None and gnd.GetNetCode() > 0
    added, seen = [], set()
    for r in rows:
        assert r['net'] == 'GND', f'r9_ground draws GND only: {r}'
        if r['item'] == 'via':
            q = (r4(float(r['x0'])), r4(float(r['y0'])))
            assert q not in seen, f'two vias at {q}'
            seen.add(q)
            assert r['layer'] == 'FB' and tuple(float(v) for v in r['size'].split('/')) == VIA, r
            v = pcbnew.PCB_VIA(b)
            v.SetPosition(P(*q))
            v.SetWidth(MM(VIA[0]))
            v.SetDrill(MM(VIA[1]))
            v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
            v.SetNet(gnd)
            b.Add(v)
            added.append(q)
        elif r['item'] == 'track':
            a = (r4(float(r['x0'])), r4(float(r['y0'])))
            c = (r4(float(r['x1'])), r4(float(r['y1'])))
            assert a != c and octilinear(a, c), f'track {a}-{c} is zero-length or not 0 / 45 / 90 degrees'
            t = pcbnew.PCB_TRACK(b)
            t.SetStart(P(*a))
            t.SetEnd(P(*c))
            t.SetWidth(MM(float(r['size'])))
            t.SetLayer(LAYER[r['layer']])
            t.SetNet(gnd)
            b.Add(t)
        else:
            raise AssertionError(f'unknown item {r} (r9_ground draws vias and tracks only: no pour trims, D-S8-03)')
    return added


def area_flags(z):
    return (z.GetDoNotAllowTracks(), z.GetDoNotAllowVias(), z.GetDoNotAllowPads(), z.GetDoNotAllowZoneFills(),
            z.GetDoNotAllowFootprints())


def zone_settings(z):
    """The fill settings XTAL_ZONE copies from XTAL_LIKE (and r9_ground_check compares)."""
    return (z.GetNetname(), list(z.GetLayerSet().Seq()), r4(mm(z.GetLocalClearance())), r4(mm(z.GetMinThickness())),
            z.GetPadConnection(), r4(mm(z.GetThermalReliefGap())), r4(mm(z.GetThermalReliefSpokeWidth())),
            z.GetIslandRemovalMode(), z.GetFillMode())


def xtal_plane(b):
    """The crystal's In2 void becomes its local ground plane (module docstring, D-S8-20); returns the new zone. Asserts
    the rule area as step 3 made it (In2 only, fills barred) and that no zone of that name exists yet."""
    zones = {z.GetZoneName(): z for z in b.Zones()}
    name, prio = XTAL_ZONE
    assert name not in zones, f'{name} already on the board (r9_ground.py runs once, on the step-7 board)'
    ko, like = zones.get(XTAL_AREA), zones.get(XTAL_LIKE)
    assert ko is not None and ko.GetIsRuleArea(), f'rule area {XTAL_AREA} missing (r9_pcb.py, R5 V1)'
    assert list(ko.GetLayerSet().Seq()) == [pcbnew.In2_Cu] and area_flags(ko) == XTAL_FLAGS_STEP3, \
        f'{XTAL_AREA} is not the In2 fill keep-out step 3 made: {area_flags(ko)}'
    assert like is not None and not like.GetIsRuleArea() and like.GetNetname() == 'GND', f'{XTAL_LIKE} missing'
    ko.SetDoNotAllowZoneFills(False)
    ko.SetDoNotAllowTracks(True)
    z = pcbnew.ZONE(b)
    z.SetLayer(pcbnew.In2_Cu)
    z.SetNet(like.GetNet())
    z.SetZoneName(name)
    z.SetAssignedPriority(prio)
    z.SetLocalClearance(like.GetLocalClearance())
    z.SetMinThickness(like.GetMinThickness())
    z.SetPadConnection(like.GetPadConnection())
    z.SetThermalReliefGap(like.GetThermalReliefGap())
    z.SetThermalReliefSpokeWidth(like.GetThermalReliefSpokeWidth())
    z.SetIslandRemovalMode(like.GetIslandRemovalMode())
    z.SetFillMode(like.GetFillMode())
    o = z.Outline()
    o.RemoveAllContours()
    o.NewOutline()
    pts, _ = xtal_outline(b, ko)
    for x, y in pts:
        o.Append(MM(x), MM(y))
    b.Add(z)
    assert zone_settings(z) == zone_settings(like)
    return z


def xtal_outline(b, ko):
    """(outline points, notches) of the crystal plane: the rule area's rectangle (asserted axis-aligned) less the
    notches of XTAL_REF_GAP's rule, each (x0, y0, x1, y1, net). One outline, no hole (asserted)."""
    pts = outline(ko)
    xs, ys = sorted({x for x, _ in pts}), sorted({y for _, y in pts})
    assert len(pts) == 4 and len(xs) == 2 and len(ys) == 2, f'{XTAL_AREA} is not an axis-aligned rectangle: {pts}'
    x0, x1, y0, y1 = xs[0], xs[1], ys[0], ys[1]
    nets = set(CR.R6_NETS) | set(CR.EXTENDED)
    notches = []
    for t in b.GetTracks():
        if t.GetClass() != 'PCB_TRACK' or t.GetLayer() != pcbnew.B_Cu or t.GetNetname() not in nets:
            continue
        a = (mm(t.GetStart().x), mm(t.GetStart().y))
        c = (mm(t.GetEnd().x), mm(t.GetEnd().y))
        n = max(1, int(math.dist(a, c) / 0.01))
        if any(x0 <= a[0] + (c[0] - a[0]) * k / n <= x1 and y0 <= a[1] + (c[1] - a[1]) * k / n <= y1
               for k in range(n + 1)):
            continue                                   # enters the area: not wholly outside
        g = mm(t.GetWidth()) / 2 + XTAL_REF_GAP
        box = (r4(max(min(a[0], c[0]) - g, x0)), r4(max(min(a[1], c[1]) - g, y0)),
               r4(min(max(a[0], c[0]) + g, x1)), r4(min(max(a[1], c[1]) + g, y1)))
        if box[0] < box[2] and box[1] < box[3]:
            notches.append(box + (t.GetNetname(),))
    poly = pcbnew.SHAPE_POLY_SET()
    poly.NewOutline()
    for x, y in box_points((x0, y0, x1, y1)):
        poly.Append(MM(x), MM(y))
    for bx in sorted(notches):
        cut = pcbnew.SHAPE_POLY_SET()
        cut.NewOutline()
        for x, y in box_points(bx[:4]):
            cut.Append(MM(x), MM(y))
        poly.BooleanSubtract(cut)
    assert poly.OutlineCount() == 1 and poly.HoleCount(0) == 0, f'{XTAL_ZONE[0]}: notches {notches} split the plane'
    o = poly.Outline(0)
    return [(r4(mm(o.CPoint(i).x)), r4(mm(o.CPoint(i).y))) for i in range(o.PointCount())], sorted(notches)


def strip_via_pads(b):
    """Every via: pads only on the layers it connects, the start and end layers kept (D-S8-19); returns the count."""
    n = 0
    for v in b.GetTracks():
        if v.GetClass() == 'PCB_VIA':
            ps = v.Padstack()
            assert ps.UnconnectedLayerMode() == pcbnew.UNCONNECTED_LAYER_MODE_KEEP_ALL, \
                f'via at ({mm(v.GetPosition().x)}, {mm(v.GetPosition().y)}) is not a step-7 via (pads on every layer)'
            ps.SetUnconnectedLayerMode(VIA_MODE)
            n += 1
    return n


def foreign_fill(b, qs):
    """Table vias whose centre lies inside a non-GND F.Cu / B.Cu fill (a stitching via must not cut a power pour)."""
    out = []
    for z in b.Zones():
        if z.GetIsRuleArea() or z.GetNetname() == 'GND':
            continue
        for lid in (pcbnew.F_Cu, pcbnew.B_Cu):
            if z.IsOnLayer(lid) and z.HasFilledPolysForLayer(lid):
                f = z.GetFilledPolysList(lid)
                out += [(q, z.GetNetname(), pcbnew.LayerName(lid)) for q in qs if f.Contains(P(*q))]
    return out


def build(b, rows):
    grow_pours(b)
    for z in b.Zones():
        if not z.GetIsRuleArea():
            z.UnFill()                     # stale fills would re-net new vias (R8 spike (c))
    added = draw(b, rows)
    xtal_plane(b)
    strip_via_pads(b)
    b.BuildConnectivity()
    assert pcbnew.ZONE_FILLER(b).Fill(b.Zones()), 'native zone fill failed'
    b.BuildConnectivity()
    moved = [(q, v.GetNetname()) for v in b.GetTracks() if v.GetClass() == 'PCB_VIA'
             for q in [(r4(mm(v.GetPosition().x)), r4(mm(v.GetPosition().y)))] if q in set(added) and
             v.GetNetname() != 'GND']
    assert not moved, f'connectivity re-netted GND vias (a via sits on foreign copper): {moved}'
    cut = foreign_fill(b, added)
    assert not cut, f'stitching vias inside a non-GND outer fill: {cut}'
    return added


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--board', type=Path, default=PROJECT / 'm3.kicad_pcb')
    ap.add_argument('--table', type=Path, default=TABLE)
    ap.add_argument('--out', type=Path, help='design aid: save here instead of --board')
    args = ap.parse_args()
    board = args.board.resolve()
    for ext in ('.kicad_pro', '.kicad_dru'):
        assert board.with_suffix(ext).is_file(), f'{board.with_suffix(ext).name} must sit beside the board'
    rows = read(args.table)
    b = pcbnew.LoadBoard(str(board))
    dup = existing(b, rows)
    assert not dup, f'{len(dup)} table items already on the board (run r9_ground.py once, on the step-7 board)'
    pcbnew.KIID.SeedGenerator(KIID_SEED)
    added = build(b, rows)
    out = (args.out or board).resolve()
    assert pcbnew.SaveBoard(str(out), b, True), 'save failed'
    tracks = sum(1 for r in rows if r['item'] == 'track')
    print(f'r9_ground: 3 GND pours grown to the board, {len(added)} GND vias, {tracks} GND track(s); the crystal\'s '
          f'In2 GND plane {XTAL_ZONE[0]}; every via\'s unconnected inner pads removed')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
