RUNS = PAD_RUNS + HAND_RUNS + SECOND_RUNS
VIAS = PAD_VIAS + HAND_VIAS + SECOND_VIAS


def plane(board, layer, name):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    z.SetNet(board.FindNet('GND'))
    z.SetAssignedPriority(0)
    # as D-R11-46's In2 3V3 base fill: 0.12 mm clearance, 0.1 mm minimum width, so the plane stays continuous between
    # two vias 0.8 mm apart in the ball field (the hole clearance 0.25 mm sets the antipads there) and the F / B / In3
    # critical runs keep their reference (check_r11 K-reference)
    z.SetLocalClearance(pcbnew.FromMM(0.12))
    z.SetMinThickness(pcbnew.FromMM(0.1))
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    z.SetThermalReliefGap(pcbnew.FromMM(0.25))
    z.SetThermalReliefSpokeWidth(pcbnew.FromMM(0.3))
    z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
    z.SetZoneName(name)
    ol = z.Outline()
    ol.NewOutline()
    for x, y in OUTLINE:
        ol.Append(pcbnew.FromMM(x), pcbnew.FromMM(y))
    board.Add(z)


# GAP-3 (AGENTS section 3, D-R11-80): R10's two resin-filled, copper-capped 0.5 / 0.3 GND thermal vias in U401.11, at
# the TI DSK0010A footprint-local centres (-0.3, 0) / (+0.3, 0) (check_r10.VIPPO_LOCAL_CENTRES); U401 at (41.5, 22.4),
# rotation 0, top face. They carry the exposed pad's heat to In1 / In4 GND and the bottom face.
VIPPO = ((41.2, 22.4), (41.8, 22.4))


def draw(d):
    for net, layer, width, pts in RUNS:
        d.track(net, layer, width, [d.pad(p[0], p[1], net=net) if isinstance(p[0], str) else p for p in pts])
    for net, at, size in VIAS:
        d.via(net, at, size)
    for at in VIPPO:
        d.vippo('GND', at)
    if not d.dry:
        plane(d.board, pcbnew.In1_Cu, 'In1_GND')
        plane(d.board, pcbnew.In4_Cu, 'In4_GND')
