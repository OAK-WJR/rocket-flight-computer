static uint32_t read_register(void *ctx,uint32_t address,unsigned width) {
    (void)ctx;
    if (width==16u) return *(volatile const uint16_t *)(uintptr_t)address;
    return *(volatile const uint32_t *)(uintptr_t)address;
}
static void write_register(void *ctx,uint32_t address,uint32_t value,unsigned width) {
    (void)ctx;(void)width;*(volatile uint32_t *)(uintptr_t)address=value;__DSB();
}
static r10_adc_port port={.io={.read=read_register,.write=write_register}};
static const r10_voltage_io io={.context=&port,.initialize=r10_adc_initialize,
    .start=r10_adc_start,.poll=r10_adc_poll,.cancel=r10_adc_cancel};
const r10_voltage_io *r10_native_voltage_io(void) {return &io;}

const r10_adc_port *r10_native_adc_state(void) {return &port;}
