static uint32_t read_mmio(void *ctx,uint32_t address,unsigned width) {
    (void)ctx;(void)width;
    return *(volatile uint32_t *)(uintptr_t)address;
}
static void write_mmio(void *ctx,uint32_t address,uint32_t value,unsigned width) {
    (void)ctx;(void)width;
    *(volatile uint32_t *)(uintptr_t)address=value;
    __DSB();
}
static void delay_cycles(void *ctx,unsigned cycles) {
    (void)ctx;for (unsigned i=0;i<cycles;++i)__NOP();
}
static r10_i2c_port port={.io={.read=read_mmio,.write=write_mmio,.delay_cycles=delay_cycles},.poll_limit=65536};
static const r10_baro_io io={.handle=&port,.initialize=r10_i2c_initialize,.transfer=r10_i2c_transfer};
const r10_baro_io *r10_native_baro_io(void) {return &io;}
